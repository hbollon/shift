#!/usr/bin/env python3
"""Install or remove the development version of Shift on the running Noctalia v5.

install    adds this checkout as a `path` plugin source, enables hbollon/shift, adds the
           bar widget and the control-center tile when no bar or shortcut has them yet,
           and reloads the config.
uninstall  disables the plugin, removes the source and the generated config file, and
           reloads the config. Shift's data is kept.

The widget and the tile are added through a generated config file: Noctalia replaces
arrays across config files instead of merging them, so the file repeats the current bar
section and shortcut list with Shift added. Edits made from Noctalia's settings still win.

Usage: scripts/dev-install.py install|uninstall
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = "hbollon/shift"
SOURCE = "shift-dev"
WIDGET = "shift"
WIDGET_TYPE = f"{PLUGIN}:bar"
TILE_TYPE = f"{PLUGIN}:tile"
CONFIG_DIR = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "noctalia"
OVERLAY = CONFIG_DIR / "zz-shift-dev.toml"
MARKER = "# Generated by `make dev-install`"
OPTIONAL_TOOLS = {
    "swayidle": "idle detection (Assisted and Automatic presets)",
    "gdbus": "session lock and sleep detection",
}


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def step(message: str) -> None:
    print(f"  {message}")


def noctalia(*args: str, check: bool = True) -> str:
    result = subprocess.run(["noctalia", *args], capture_output=True, text=True)
    if check and result.returncode != 0:
        fail(f"`noctalia {' '.join(args)}` failed: {(result.stderr or result.stdout).strip()}")
    return result.stdout


def config() -> dict:
    return tomllib.loads(noctalia("config", "export", "full"))


def sources(cfg: dict) -> list[dict]:
    return cfg.get("plugins", {}).get("source", [])


def enabled(cfg: dict) -> bool:
    return PLUGIN in cfg.get("plugins", {}).get("enabled", [])


def toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        return "[ " + ", ".join(toml_value(item) for item in value) + " ]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {toml_value(item)}" for key, item in value.items()) + " }"
    raise TypeError(f"unsupported TOML value: {value!r}")


def widget_names(cfg: dict) -> set[str]:
    """Names that render Shift's bar widget: declared instances, plus the bare type."""
    widgets = cfg.get("widget", {})
    names = {name for name, spec in widgets.items() if isinstance(spec, dict) and spec.get("type") == WIDGET_TYPE}
    return names | {WIDGET_TYPE}


def bar_has_widget(cfg: dict) -> bool:
    names = widget_names(cfg)
    for bar in cfg.get("bar", {}).values():
        if isinstance(bar, dict) and any(name in names for side in ("start", "center", "end") for name in bar.get(side, [])):
            return True
    return False


def shortcuts(cfg: dict) -> list[dict]:
    return cfg.get("control_center", {}).get("shortcuts", [])


def overlay(cfg: dict) -> str | None:
    """Config text that adds the missing widget and tile, or None when both are present."""
    lines = [f"{MARKER} in {ROOT}.", "# `make dev-uninstall` removes it.", ""]
    changed = False
    bars = cfg.get("bar", {})
    order = bars.get("order") or [name for name, bar in bars.items() if isinstance(bar, dict)]
    if not bar_has_widget(cfg) and order:
        name = order[0]
        # Avoid shadowing a widget the user already calls `shift`.
        taken = set(cfg.get("widget", {})) | {
            entry for bar in bars.values() if isinstance(bar, dict) for side in ("start", "center", "end") for entry in bar.get(side, [])
        }
        widget = WIDGET if WIDGET not in taken else f"{WIDGET}_dev"
        lines += [f"[widget.{widget}]", f"type = {toml_value(WIDGET_TYPE)}", ""]
        lines += [f"[bar.{name}]", f"end = {toml_value([widget, *bars[name].get('end', [])])}", ""]
        step(f"adding the widget to the start of the `{name}` bar's end section")
        changed = True
    tiles = shortcuts(cfg)
    if not any(tile.get("type") == TILE_TYPE for tile in tiles):
        for tile in [*tiles, {"type": TILE_TYPE}]:
            lines += ["[[control_center.shortcuts]]"]
            lines += [f"{key} = {toml_value(value)}" for key, value in tile.items()]
            lines += [""]
        step("adding the tile to the control center")
        changed = True
    return "\n".join(lines) if changed else None


def owns_overlay() -> bool:
    return OVERLAY.exists() and OVERLAY.read_text().startswith(MARKER)


def install() -> None:
    cfg = config()
    dev = [s for s in sources(cfg) if s.get("kind") == "path" and Path(s.get("location", "")) == ROOT]
    if dev:
        step(f"plugin source `{dev[0]['name']}` already points at {ROOT}")
    else:
        if any(s.get("name") == SOURCE for s in sources(cfg)):
            step(f"replacing plugin source `{SOURCE}`")
            noctalia("msg", "plugins", "source", "remove", SOURCE)
        step(f"adding plugin source `{SOURCE}` -> {ROOT}")
        noctalia("msg", "plugins", "source", "add", SOURCE, "path", str(ROOT))

    listing = [line for line in noctalia("msg", "plugins", "list").splitlines() if line.startswith(PLUGIN + " ")]
    if not listing:
        fail(f"Noctalia does not list {PLUGIN}; check `noctalia msg plugins list`")
    if not enabled(cfg):
        step(f"enabling {PLUGIN}")
        noctalia("msg", "plugins", "enable", PLUGIN)
    else:
        step(f"{PLUGIN} already enabled")

    text = overlay(config())
    if text is not None:
        if OVERLAY.exists() and not owns_overlay():
            fail(f"{OVERLAY} exists and was not generated by this script; move it away and retry")
        OVERLAY.write_text(text)
        step(f"wrote {OVERLAY}")
    noctalia("msg", "config-reload")

    cfg = config()
    if text is not None and not (bar_has_widget(cfg) and any(t.get("type") == TILE_TYPE for t in shortcuts(cfg))):
        step("warning: your Noctalia settings override the generated file; add the widget and tile from the settings")
    listing = [line for line in noctalia("msg", "plugins", "list").splitlines() if line.startswith(PLUGIN + " ")]
    print(f"\n{listing[0] if listing else PLUGIN}")
    if listing and f"[{SOURCE}]" not in listing[0] and not dev:
        step(f"warning: {PLUGIN} is served by another source; remove it to run this checkout")
    for tool, purpose in OPTIONAL_TOOLS.items():
        if shutil.which(tool) is None:
            step(f"note: `{tool}` not found, needed for {purpose}")
    print("\nOpen the panel with `noctalia msg panel-toggle hbollon/shift:dashboard`. Remove with `make dev-uninstall`.")


def uninstall() -> None:
    cfg = config()
    if enabled(cfg):
        step(f"disabling {PLUGIN}")
        noctalia("msg", "plugins", "disable", PLUGIN)
    for source in sources(cfg):
        if source.get("kind") == "path" and Path(source.get("location", "")) == ROOT:
            step(f"removing plugin source `{source['name']}`")
            noctalia("msg", "plugins", "source", "remove", source["name"])
    if owns_overlay():
        OVERLAY.unlink()
        step(f"removed {OVERLAY}")
    elif OVERLAY.exists():
        step(f"kept {OVERLAY}: not generated by this script")
    noctalia("msg", "config-reload")
    print("\nShift's data is kept in ~/.local/state/noctalia/plugins/data/hbollon/shift/.")


def main() -> None:
    if len(sys.argv) != 2 or sys.argv[1] not in ("install", "uninstall"):
        fail("usage: scripts/dev-install.py install|uninstall")
    if shutil.which("noctalia") is None:
        fail("noctalia is not installed")
    if subprocess.run(["noctalia", "msg", "plugins", "list"], capture_output=True).returncode != 0:
        fail("Noctalia is not running; start it first")
    install() if sys.argv[1] == "install" else uninstall()


if __name__ == "__main__":
    main()
