#!/usr/bin/env python3
"""Generate the root catalog.toml from shift/plugin.toml.

The catalog lets users add this repository as a Noctalia git source: Noctalia lists and
compat-checks plugins from it without a full clone. It must mirror the manifest, so it
is generated, never edited by hand.

Usage: scripts/catalog.py [--check]
  --check  exit 1 if catalog.toml is not up to date (used by CI)
"""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "shift" / "plugin.toml"
CATALOG = ROOT / "catalog.toml"

# Catalog fields, in output order, with their defaults when the manifest omits them.
FIELDS = (
    ("id", None),
    ("name", None),
    ("version", None),
    ("author", None),
    ("license", "MIT"),
    ("icon", None),
    ("description", None),
    ("deprecated", False),
    ("plugin_api", None),
    ("tags", []),
    ("dependencies", []),
)


def render(manifest: dict) -> str:
    lines = ["# Generated by scripts/catalog.py from shift/plugin.toml. Do not edit.", "", "[[plugin]]"]
    width = max(len(name) for name, _ in FIELDS)
    for name, default in FIELDS:
        value = manifest.get(name, default)
        if value is None:
            continue
        # JSON literals for strings, bools, ints and string arrays are valid TOML.
        lines.append(f"{name.ljust(width)} = {json.dumps(value, ensure_ascii=False)}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    with MANIFEST.open("rb") as f:
        expected = render(tomllib.load(f))
    if "--check" in argv:
        current = CATALOG.read_text(encoding="utf-8") if CATALOG.exists() else ""
        if current != expected:
            print("catalog.toml is out of date, run 'make catalog'", file=sys.stderr)
            return 1
        print("catalog.toml is up to date")
        return 0
    CATALOG.write_text(expected, encoding="utf-8")
    print(f"wrote {CATALOG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
